import { useState } from 'react';

/**
 * Export button that generates a Markdown report and copies to clipboard / downloads.
 */
export default function ExportButton({
  repoName,
  healthScore,
  grade,
  factors,
  predictions,
  repoInfo,
}) {
  const [copied, setCopied] = useState(false);

  const generateMarkdown = () => {
    const now = new Date().toISOString().split('T')[0];

    let md = `# GitPulse AI — Repository Health Report\n`;
    md += `**Repository:** ${repoName}\n`;
    md += `**Generated:** ${now}\n`;
    md += `**Overall Score:** ${healthScore}/100 (Grade: ${grade})\n\n`;

    if (repoInfo) {
      md += `## Repository Overview\n`;
      md += `| Metric | Value |\n|--------|-------|\n`;
      md += `| Stars | ${repoInfo.stargazers_count?.toLocaleString()} |\n`;
      md += `| Forks | ${repoInfo.forks_count?.toLocaleString()} |\n`;
      md += `| Open Issues | ${repoInfo.open_issues_count?.toLocaleString()} |\n`;
      md += `| License | ${repoInfo.license?.spdx_id || 'None'} |\n`;
      md += `| Created | ${new Date(repoInfo.created_at).toLocaleDateString()} |\n\n`;
    }

    md += `## Health Score Breakdown\n`;
    md += `| Factor | Score | Weight | Details |\n|--------|-------|--------|--------|\n`;

    if (factors) {
      Object.values(factors).forEach((f) => {
        md += `| ${f.icon} ${f.label} | ${f.score}/100 | ${Math.round(
          f.weight * 100
        )}% | ${f.detail} |\n`;
      });
    }

    md += '\n';

    if (predictions?.length) {
      md += `## Predictive Insights\n`;

      predictions.forEach((p) => {
        md += `- ${p.icon} **${p.title}** — ${p.description}\n`;
      });

      md += '\n';
    }

    md += `---\n*Report generated by [GitPulse AI](https://gitpulse.ai) — Powered by Model Context Protocol*\n`;

    return md;
  };

  const handleCopy = async () => {
    const md = generateMarkdown();

    try {
      await navigator.clipboard.writeText(md);

      setCopied(true);

      setTimeout(() => {
        setCopied(false);
      }, 2500);
    } catch {
      const ta = document.createElement('textarea');

      ta.value = md;

      document.body.appendChild(ta);

      ta.select();

      document.execCommand('copy');

      document.body.removeChild(ta);

      setCopied(true);

      setTimeout(() => {
        setCopied(false);
      }, 2500);
    }
  };

  const handleDownload = () => {
    const md = generateMarkdown();

    const blob = new Blob([md], {
      type: 'text/markdown',
    });

    const url = URL.createObjectURL(blob);

    const a = document.createElement('a');

    a.href = url;

    a.download = `gitpulse-report-${repoName?.replace(
      '/',
      '-'
    )}-${Date.now()}.md`;

    a.click();

    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex flex-wrap gap-2.5">

      {/* COPY REPORT */}
      <button
        onClick={handleCopy}
        className={`inline-flex cursor-pointer items-center gap-1.5 rounded-lg border px-3.5 py-2 text-xs font-semibold shadow-sm transition-all ${
          copied
            ? 'border-emerald-200 bg-emerald-50 text-emerald-600 hover:bg-emerald-100'
            : 'border-blue-200 bg-white text-blue-600 hover:border-blue-400 hover:bg-blue-50 hover:text-blue-700'
        }`}
      >
        {copied ? '✓ Copied!' : '📋 Copy Report'}
      </button>

      {/* DOWNLOAD */}
      <button
        onClick={handleDownload}
        className="inline-flex cursor-pointer items-center gap-1.5 rounded-lg border border-blue-200 bg-white px-3.5 py-2 text-xs font-semibold text-blue-600 shadow-sm transition-all hover:border-blue-400 hover:bg-blue-50 hover:text-blue-700"
      >
        📥 Download .md
      </button>

    </div>
  );
}