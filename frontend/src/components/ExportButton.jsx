import { useState } from 'react';

/**
 * Export button that generates a Markdown report and copies to clipboard / downloads.
 */
export default function ExportButton({ repoName, healthScore, grade, factors, predictions, repoInfo }) {
  const [copied, setCopied] = useState(false);

  const generateMarkdown = () => {
    const now = new Date().toISOString().split('T')[0];
    let md = `# GitPulse AI — Repository Health Report\n`;
    md += `**Repository:** ${repoName}\n`;
    md += `**Generated:** ${now}\n`;
    md += `**Overall Score:** ${healthScore}/100 (Grade: ${grade})\n\n`;

    if (repoInfo) {
      md += `## Repository Overview\n`;
      md += `| Metric | Value |\n|--------|-------|\n`;
      md += `| Stars | ${repoInfo.stargazers_count?.toLocaleString()} |\n`;
      md += `| Forks | ${repoInfo.forks_count?.toLocaleString()} |\n`;
      md += `| Open Issues | ${repoInfo.open_issues_count?.toLocaleString()} |\n`;
      md += `| License | ${repoInfo.license?.spdx_id || 'None'} |\n`;
      md += `| Created | ${new Date(repoInfo.created_at).toLocaleDateString()} |\n\n`;
    }

    md += `## Health Score Breakdown\n`;
    md += `| Factor | Score | Weight | Details |\n|--------|-------|--------|--------|\n`;
    if (factors) {
      Object.values(factors).forEach((f) => {
        md += `| ${f.icon} ${f.label} | ${f.score}/100 | ${Math.round(f.weight * 100)}% | ${f.detail} |\n`;
      });
    }
    md += '\n';

    if (predictions?.length) {
      md += `## Predictive Insights\n`;
      predictions.forEach((p) => {
        md += `- ${p.icon} **${p.title}** — ${p.description}\n`;
      });
      md += '\n';
    }

    md += `---\n*Report generated by [GitPulse AI](https://gitpulse.ai) — Powered by Model Context Protocol*\n`;
    return md;
  };

  const handleCopy = async () => {
    const md = generateMarkdown();
    try {
      await navigator.clipboard.writeText(md);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      // Fallback
      const ta = document.createElement('textarea');
      ta.value = md;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand('copy');
      document.body.removeChild(ta);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    }
  };

  const handleDownload = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `gitpulse-report-${repoName?.replace('/', '-')}-${Date.now()}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const btnBase = {
    display: 'inline-flex', alignItems: 'center', gap: 6,
    padding: '8px 16px',
    fontSize: 13, fontWeight: 600,
    fontFamily: 'var(--font-sans)',
    border: '1px solid var(--border)',
    borderRadius: 'var(--radius-sm)',
    cursor: 'pointer',
    transition: 'all 0.2s ease',
    background: 'var(--bg-card)',
    color: 'var(--text-primary)',
  };

  return (
    <div style={{ display: 'flex', gap: 10, flexWrap: 'wrap' }}>
      <button
        onClick={handleCopy}
        style={{
          ...btnBase,
          background: copied ? 'rgba(16,185,129,0.15)' : 'var(--bg-card)',
          borderColor: copied ? 'rgba(16,185,129,0.3)' : 'var(--border)',
          color: copied ? '#10b981' : 'var(--text-primary)',
        }}
        onMouseEnter={(e) => { if (!copied) e.currentTarget.style.borderColor = 'var(--border-hover)'; }}
        onMouseLeave={(e) => { if (!copied) e.currentTarget.style.borderColor = 'var(--border)'; }}
      >
        {copied ? '✓ Copied!' : '📋 Copy Report'}
      </button>
      <button
        onClick={handleDownload}
        style={btnBase}
        onMouseEnter={(e) => { e.currentTarget.style.borderColor = 'var(--border-hover)'; }}
        onMouseLeave={(e) => { e.currentTarget.style.borderColor = 'var(--border)'; }}
      >
        📥 Download .md
      </button>
    </div>
  );
}
